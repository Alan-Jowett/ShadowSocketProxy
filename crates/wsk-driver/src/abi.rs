/// Legacy bounded forwarding metadata retained for ABI compatibility.
///
/// The live WSK path uses [`MappingWaitRequest`], [`MappingRequest`], and
/// [`MappingCompletion`] and never sends payload bytes through an IOCTL.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ForwardRequest {
    /// Common request header.
    pub header: AbiHeader,
    /// IP protocol number (TCP or UDP).
    pub protocol: u8,
    /// Address family: 4 or 6.
    pub address_family: u8,
    /// Reserved for ABI alignment and future flags.
    pub reserved: u16,
    /// Source port in host byte order.
    pub source_port: u16,
    /// Destination port in host byte order.
    pub destination_port: u16,
    /// Source address in network byte order, IPv4 stored in the first four
    /// bytes.
    pub source_address: [u8; 16],
    /// Destination address in network byte order, IPv4 stored in the first
    /// four bytes.
    pub destination_address: [u8; 16],
    /// Payload bytes carried in the corresponding IOCTL buffer.
    pub payload_length: u32,
}

