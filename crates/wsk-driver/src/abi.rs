//! Fixed-layout, versioned user/kernel device messages.

use core::{fmt, mem::size_of};

/// Current device ABI version.
pub const ABI_VERSION: u16 = 1;
/// Number of bytes in every session nonce.
pub const SESSION_NONCE_SIZE: usize = 32;
/// Default Windows device path exposed by the broker component.
pub const DEVICE_PATH: &str = r"\\.\ShadowSocketProxy";
/// Maximum request payload accepted by the device contract.
pub const MAX_PAYLOAD_SIZE: usize = 16 * 1024;
/// Maximum time the driver keeps a broker mapping exchange outstanding.
pub const MAPPING_TIMEOUT_MS: u64 = 5_000;

/// Stable status values exchanged over the device boundary.
#[repr(u32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    /// The operation completed successfully.
    Ok = 0,
    /// The caller supplied an unsupported ABI version or structure size.
    InvalidAbi = 1,
    /// The session nonce does not match the open broker session.
    InvalidSession = 2,
    /// The request ID or generation is invalid or stale.
    InvalidIdentity = 3,
    /// The request is not valid for the current device state.
    InvalidState = 4,
    /// The requested operation is not supported by this component.
    NotSupported = 5,
    /// A required WSK or device resource is unavailable.
    ResourceUnavailable = 6,
    /// The device operation was cancelled.
    Cancelled = 7,
    /// An unspecified device failure occurred.
    InternalError = 8,
    /// The synthetic or original tuple failed exact mapping validation.
    InvalidMapping = 9,
    /// The bounded mapping wait expired without a flow.
    Timeout = 10,
}

impl Status {
    /// Converts a wire value without accepting unknown status values.
    pub const fn from_raw(value: u32) -> Option<Self> {
        match value {
            0 => Some(Self::Ok),
            1 => Some(Self::InvalidAbi),
            2 => Some(Self::InvalidSession),
            3 => Some(Self::InvalidIdentity),
            4 => Some(Self::InvalidState),
            5 => Some(Self::NotSupported),
            6 => Some(Self::ResourceUnavailable),
            7 => Some(Self::Cancelled),
            8 => Some(Self::InternalError),
            9 => Some(Self::InvalidMapping),
            10 => Some(Self::Timeout),
            _ => None,
        }
    }
}

/// Device operations. Values are part of the versioned ABI.
#[repr(u32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Opcode {
    /// Establishes a broker session and returns the device nonce.
    OpenSession = 1,
    /// Closes a broker session.
    CloseSession = 2,
    /// Submits a forwarding request to the device.
    SubmitRequest = 3,
    /// Retrieves a completed forwarding request.
    CompleteRequest = 4,
}

impl Opcode {
    /// Converts a wire value without accepting unknown opcodes.
    pub const fn from_raw(value: u32) -> Option<Self> {
        match value {
            1 => Some(Self::OpenSession),
            2 => Some(Self::CloseSession),
            3 => Some(Self::SubmitRequest),
            4 => Some(Self::CompleteRequest),
            _ => None,
        }
    }
}

/// Fixed-size nonce identifying one broker/device session.
#[repr(C)]
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
pub struct SessionNonce {
    /// Opaque nonce bytes generated by the device.
    pub bytes: [u8; SESSION_NONCE_SIZE],
}

impl SessionNonce {
    /// Creates a nonce from fixed-size bytes.
    pub const fn new(bytes: [u8; SESSION_NONCE_SIZE]) -> Self {
        Self { bytes }
    }

    /// Returns the all-zero nonce used only as an invalid sentinel.
    pub const fn zero() -> Self {
        Self {
            bytes: [0; SESSION_NONCE_SIZE],
        }
    }

    /// Rejects the invalid all-zero session identity.
    pub const fn is_zero(&self) -> bool {
        let mut index = 0;
        while index < SESSION_NONCE_SIZE {
            if self.bytes[index] != 0 {
                return false;
            }
            index += 1;
        }
        true
    }
}

impl fmt::Debug for SessionNonce {
    /// Redacts the nonce while retaining a useful type label.
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_tuple("SessionNonce")
            .field(&"[redacted]")
            .finish()
    }
}

/// Monotonic broker request identity.
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct RequestId(pub u64);

/// Monotonic request incarnation used to reject stale completions.
#[repr(transparent)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Generation(pub u64);

/// Common header present at the start of every device message.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AbiHeader {
    /// ABI version of the message.
    pub version: u16,
    /// Complete structure size in bytes.
    pub size: u16,
    /// Operation code.
    pub opcode: u32,
    /// Device status; requests use `Status::Ok`.
    pub status: u32,
    /// Session identity.
    pub session_nonce: SessionNonce,
    /// Explicitly zeroed replacement for the C ABI alignment padding.
    pub reserved: u32,
    /// Request identity.
    pub request_id: RequestId,
    /// Request incarnation.
    pub generation: Generation,
}

impl AbiHeader {
    /// Creates a request header with a validated ABI version and identity.
    pub const fn request(
        opcode: Opcode,
        nonce: SessionNonce,
        request_id: RequestId,
        generation: Generation,
        size: usize,
    ) -> Self {
        Self {
            version: ABI_VERSION,
            size: size as u16,
            opcode: opcode as u32,
            status: Status::Ok as u32,
            session_nonce: nonce,
            reserved: 0,
            request_id,
            generation,
        }
    }

    /// Creates a response header preserving the request identity.
    pub const fn response(
        opcode: Opcode,
        status: Status,
        nonce: SessionNonce,
        request_id: RequestId,
        generation: Generation,
        size: usize,
    ) -> Self {
        Self {
            version: ABI_VERSION,
            size: size as u16,
            opcode: opcode as u32,
            status: status as u32,
            session_nonce: nonce,
            reserved: 0,
            request_id,
            generation,
        }
    }

    /// Validates the version, size, opcode, and request status fields.
    pub fn validate_envelope(&self, opcode: Opcode, expected_size: usize) -> Result<(), AbiError> {
        if self.version != ABI_VERSION || self.size as usize != expected_size {
            return Err(AbiError::InvalidAbi);
        }
        if Opcode::from_raw(self.opcode) != Some(opcode) {
            return Err(AbiError::InvalidOpcode);
        }
        if self.status != Status::Ok as u32 {
            return Err(AbiError::InvalidStatus(self.status));
        }
        if self.reserved != 0 {
            return Err(AbiError::InvalidAbi);
        }
        Ok(())
    }

    /// Validates common wire fields and the expected operation and size.
    pub fn validate(
        &self,
        opcode: Opcode,
        expected_size: usize,
        expected_nonce: Option<SessionNonce>,
    ) -> Result<(), AbiError> {
        self.validate_envelope(opcode, expected_size)?;
        if self.request_id.0 == 0 || self.generation.0 == 0 {
            return Err(AbiError::InvalidIdentity);
        }
        if let Some(expected) = expected_nonce {
            if self.session_nonce != expected {
                return Err(AbiError::InvalidSession);
            }
        } else if self.session_nonce.is_zero() {
            return Err(AbiError::InvalidSession);
        }
        Ok(())
    }

    /// Validates that a response belongs to the supplied request identity.
    pub fn validate_identity(
        &self,
        request_id: RequestId,
        generation: Generation,
    ) -> Result<(), AbiError> {
        if self.request_id != request_id || self.generation != generation {
            return Err(AbiError::InvalidIdentity);
        }
        Ok(())
    }

    /// Validates a response envelope while preserving its device status.
    pub fn validate_response(
        &self,
        opcode: Opcode,
        expected_size: usize,
        expected_nonce: SessionNonce,
        request_id: RequestId,
        generation: Generation,
    ) -> Result<Status, AbiError> {
        self.validate_response_envelope(opcode, expected_size)?;
        let status = Status::from_raw(self.status).ok_or(AbiError::InvalidStatus(self.status))?;
        if self.session_nonce != expected_nonce {
            return Err(AbiError::InvalidSession);
        }
        self.validate_identity(request_id, generation)?;
        Ok(status)
    }

    /// Validates response fields that are independent of the device status.
    pub fn validate_response_envelope(
        &self,
        opcode: Opcode,
        expected_size: usize,
    ) -> Result<(), AbiError> {
        if self.version != ABI_VERSION || self.size as usize != expected_size {
            return Err(AbiError::InvalidAbi);
        }
        if Opcode::from_raw(self.opcode) != Some(opcode) {
            return Err(AbiError::InvalidOpcode);
        }
        if self.reserved != 0 {
            return Err(AbiError::InvalidAbi);
        }
        Ok(())
    }

    /// Validates a new request identity against the previous operation.
    pub fn validate_next_identity(
        &self,
        previous_request_id: RequestId,
        previous_generation: Generation,
    ) -> Result<(), AbiError> {
        if self.request_id.0 == 0
            || self.generation.0 == 0
            || self.request_id <= previous_request_id
            || self.generation <= previous_generation
        {
            return Err(AbiError::InvalidIdentity);
        }
        Ok(())
    }
}

